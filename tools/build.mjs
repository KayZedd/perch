#!/usr/bin/env node
// src/*.css -> extension/css/perch.css
// Wraps everything in @-moz-document so the agent sheet never touches web or mail content.
import { readdirSync, readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";
import { addImportant } from "./important.mjs";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const srcDir = join(root, "src");
const outFile = join(root, "extension", "css", "perch.css");

// Chrome documents mark their root with lightweightthemes="true"; web and mail
// content never does. Agent sheets apply to every document, so all non-token rules
// are scoped under this. Rules starting with :root are left as written.
export const SCOPE = ":root[lightweightthemes]";

export function build() {
  const parts = readdirSync(srcDir)
    .filter((f) => f.endsWith(".css"))
    .sort()
    .map((f) => `/* ${f} */\n` + readFileSync(join(srcDir, f), "utf8"));
  const body = addImportant(parts.join("\n"), { scope: SCOPE });
  return `/* GENERATED by tools/build.mjs from src/*.css. Do not edit. */\n${body}\n`;
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  mkdirSync(dirname(outFile), { recursive: true });
  writeFileSync(outFile, build());
  console.log("wrote", outFile);
}
